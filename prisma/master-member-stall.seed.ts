// Function แบ่งข้อมูลเป็นชุดย่อยเพื่อลดขนาด transaction ตอน seed
const chunkArray = <T>(items: T[], size: number): T[][] => {
  const chunks: T[][] = [];

  for (let index = 0; index < items.length; index += size) {
    chunks.push(items.slice(index, index + size));
  }

  return chunks;
};

// Function seed ข้อมูล master_member_stalls ลง DB
export async function seedMasterMemberStalls(prisma: PrismaClient): Promise<void> {
  const batches = chunkArray(masterMemberStallSeedData, 25);

  for (const batch of batches) {
    const operations = batch.map((item) =>
      prisma.masterMemberStall.upsert({
        where: {
          marketCode_ownerIdCard_memberStallLineUserId: {
            marketCode: item.marketCode,
            ownerIdCard: item.ownerIdCard,
            memberStallLineUserId: item.memberStallLineUserId,
          },
        },
        create: item,
        update: {
          memberStallFirstName: item.memberStallFirstName,
          memberStallLastName: item.memberStallLastName,
        },
      }),
    );

    await prisma.$transaction(operations);
  }

  console.info(
    `[seed] master_member_stalls completed: ${masterMemberStallSeedData.length} records`,
  );
}
