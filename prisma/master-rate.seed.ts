// Function seed ข้อมูล master_rate จาก master rate list ลง DB
export async function seedMasterRates(prisma: PrismaClient): Promise<void> {
  const syncedAt = new Date();

  await prisma.$transaction(
    masterRateSeeds.map((rate) =>
      prisma.masterRate.upsert({
        where: {
          sourceRateId: rate.sourceRateId,
        },
        update: {
          marketCode: rate.marketCode,
          weightRangeName: rate.weightRangeName,
          weightMin: rate.weightMin,
          weightMax: rate.weightMax,
          stallRate: rate.stallRate,
          laborRate: rate.laborRate,
          status: rate.status,
          sourceCreatedAt: rate.sourceCreatedAt,
          sourceUpdatedAt: rate.sourceUpdatedAt,
          syncedAt,
        },
        create: {
          ...rate,
          syncedAt,
        },
      }),
    ),
  );

  console.log(`Seeded ${masterRateSeeds.length} master_rate records.`);
}
